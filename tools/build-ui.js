'use strict';

// Builds ui/ (what the Tauri window shows) and src-tauri/src/channels.in (what the backend accepts) from the pinned
// Electron release in reference/electron-v1.17.1. Nothing is edited by hand, so the screens and the channel names
// cannot drift from the app they replace:
//   node tools/build-ui.js
//
//   1. ui/            the released renderer, plus two small changes to index.html (the bridge script tag, and `connect-src ipc:` in
//                     its CSP so the page may reach the backend) and the Bedrock Dedicated Server type's patches (ui-extra/, tools/ui-patches-bedrock.js).
//   2. ui/tauri-bridge.js   preload.js with ipcRenderer.invoke(...) turned into call(...) and ipcRenderer.on(...)
//                     turned into Tauri event listeners.
//   3. src-tauri/src/channels.in   every invoke channel in preload.js.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ref = path.join(root, 'reference', 'electron-v1.17.1', 'src');
const ui = path.join(root, 'ui');

fs.rmSync(ui, { recursive: true, force: true });
fs.cpSync(path.join(ref, 'renderer'), ui, { recursive: true });

// --- bridge ---------------------------------------------------------------------------------------------
const preload = fs.readFileSync(path.join(ref, 'main', 'preload.js'), 'utf8').replace(/\r\n/g, '\n');
const open = "exposeInMainWorld('vp', {";
const body = preload.slice(preload.indexOf(open) + open.length, preload.lastIndexOf('});'));
const allowed = [...body.match(/const allowed = \[([\s\S]*?)\];/)[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
// Events this build adds (web control, testers only).
allowed.push('webcontrol:event');
const onBlock = /on: \(channel, cb\) => \{[\s\S]*?\n  \},\n/;
if (!onBlock.test(body)) throw new Error('preload.js: could not find the on() block');
const converted = body
  .replace(onBlock, 'on: (channel, cb) => {\n      if (!EVENTS.has(channel)) return;\n      tauri.event.listen(channel, (evt) => cb(evt.payload));\n    },\n')
  .replace(/ipcRenderer\.invoke\(/g, 'call(');
if (/ipcRenderer/.test(converted)) throw new Error('preload.js: an ipcRenderer call was not converted');

const bridge = `'use strict';

// GENERATED by tools/build-ui.js from the Electron preload (reference/electron-v1.17.1). Do not edit by hand.
// It exposes the same \`window.vp\` object, so the renderer scripts run unchanged. Every call goes through one Rust
// command, \`ipc\`, which dispatches on the channel name; every event arrives as a Tauri event of the same name.
(() => {
  const tauri = window.__TAURI__;
  if (!tauri || !tauri.core || !tauri.event) {
    console.error('VoxelPort: the Tauri runtime is missing, so the app cannot reach its backend.');
    return;
  }

  const call = (channel, args) => tauri.core.invoke('ipc', { channel, args: args === undefined ? null : args });

  const EVENTS = new Set([
${allowed.map((c) => `    '${c}',`).join('\n')}
  ]);

  window.vp = {${converted}};
  // Added by this build (not in the Electron preload): bringing the previous app's data over, once, on the person's say-so.
  window.vp.legacyImport = {
    detect: () => call('legacy:detect'),
    run: () => call('legacy:run'),
    dismiss: () => call('legacy:dismiss'),
  };
  // Added by this build: web control (testers only; the backend answers available:false unless the app was started for it).
  window.vp.webControlGet = () => call('webcontrol:get');
  window.vp.webControlSet = (opts) => call('webcontrol:set', opts);
  window.vp.webControlInvites = () => call('webcontrol:inviteList');
  window.vp.webControlInviteCreate = (opts) => call('webcontrol:inviteCreate', opts);
  window.vp.webControlInviteRemove = (id) => call('webcontrol:inviteRemove', { id });
  window.vp.webControlOpenDashboard = () => call('webcontrol:openDashboard');
})();
`;
fs.writeFileSync(path.join(ui, 'tauri-bridge.js'), bridge);

// --- index.html ------------------------------------------------------------------------------------------
const indexPath = path.join(ui, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
if (!html.includes("script-src 'self'; base-uri 'none'")) throw new Error('index.html: CSP not in the expected form');
html = html.replace("script-src 'self'; base-uri 'none'", "script-src 'self'; connect-src ipc: http://ipc.localhost; base-uri 'none'");
if (!html.includes('<script src="theme-init.js"></script>')) throw new Error('index.html: theme-init script tag not found');
html = html.replace('<script src="theme-init.js"></script>', '<script src="theme-init.js"></script>\n  <script src="tauri-bridge.js"></script>');
fs.writeFileSync(indexPath, html);

// --- the Bedrock Dedicated Server type -----------------------------------------------------------------------
// New code lives in ui-extra/ (copied in as it is); the few places where the released screens must differ are patches
// (tools/ui-patches-bedrock.js). A patch whose anchor is missing stops the build, so a change in the pinned renderer
// can never turn one into a silent no-op.
for (const f of fs.readdirSync(path.join(root, 'ui-extra'))) fs.copyFileSync(path.join(root, 'ui-extra', f), path.join(ui, f));
const touched = new Map();
const patches = fs.readdirSync(__dirname).filter((f) => /^ui-patches-.+\.js$/.test(f)).sort().flatMap((f) => require(`./${f}`));
for (const p of patches) {
  const file = path.join(ui, p.file);
  const text = touched.get(file) ?? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  if (!text.includes(p.find)) throw new Error(`ui patch: anchor not found in ${p.file}: ${p.find.slice(0, 80)}`);
  touched.set(file, p.all ? text.split(p.find).join(p.replace) : text.replace(p.find, () => p.replace));
}
for (const [file, text] of touched) fs.writeFileSync(file, text);

// --- extra translated strings (web control) -----------------------------------------------------------------
// ui-extra/webcontrol-lang.json holds { language: { English text: translation } }; they are added to the end of each language file.
const extraLang = JSON.parse(fs.readFileSync(path.join(root, 'ui-extra', 'webcontrol-lang.json'), 'utf8'));
for (const [lang, entries] of Object.entries(extraLang)) {
  const file = path.join(ui, 'lang', `${lang}.js`);
  const text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const end = text.lastIndexOf('};');
  if (end < 0) throw new Error(`lang/${lang}.js: closing brace not found`);
  const quote = (v) => v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const add = Object.entries(entries).filter(([k]) => !text.includes(`'${quote(k)}':`)).map(([k, v]) => `  '${quote(k)}': '${quote(v)}',\n`).join('');
  fs.writeFileSync(file, text.slice(0, end) + add + text.slice(end));
}

// --- channel allow-list for the Rust side ------------------------------------------------------------------
// The channels the Electron preload knows, plus the ones this build adds (bringing the previous app's data over).
const EXTRA_CHANNELS = ['legacy:detect', 'legacy:dismiss', 'legacy:run', 'webcontrol:get', 'webcontrol:set', 'webcontrol:inviteList', 'webcontrol:inviteCreate', 'webcontrol:inviteRemove', 'webcontrol:openDashboard'];
const channels = [...new Set([...[...preload.matchAll(/invoke\('([^']+)'/g)].map((m) => m[1]), ...EXTRA_CHANNELS])].sort();
fs.writeFileSync(path.join(root, 'src-tauri', 'src', 'channels.in'), '&[\n' + channels.map((c) => `    "${c}",`).join('\n') + '\n]\n');

console.log(`ui/ built: ${channels.length} call channels, ${allowed.length} event channels`);
